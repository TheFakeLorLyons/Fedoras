(def encounters
  "Face on the die to passage, derived from the roster so the two can
  never disagree about which animal is which."
  (into (sorted-map)
        (map (fn [[face {:keys [animal]}]]
               [face (get passages-by-animal animal)]))
        companions/roster))

(defn animals-without-passages
  "Animals on the roster this session has nothing written for. Empty
  when the file is finished, and worth checking in every new session
  file before it ships."
  []
  (->> (vals companions/roster)
       (map :animal)
       (remove #(contains? passages-by-animal %))
       vec))

(defn what-it-did
  "The passage for whichever animal the reader rolled."
  []
  (sessions/passage "one" encounters))