(ns fedoras.sessions.one
  "SESSION ONE. What the animal does when the hound comes.

  One passage per animal, keyed by the animal's name, so the roster can
  be reordered and every passage still reaches its own animal. The
  reader rolled an animal earlier in the same scene; this is what it
  did when the hound came up the corridor for the ledger.

  Every session of the campaign gets a file like this one."
  (:require [fedoras.companions :as companions]
            [fedoras.sessions :as sessions]))

